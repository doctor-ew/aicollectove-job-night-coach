#!/usr/bin/env python3
"""Embed the canonical coach text for opening the starter directly from disk."""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent

def generated():
    source = (ROOT / 'coach/START-HERE.md').read_bytes()
    text = source.decode('utf-8')
    header = '// Generated by starter/build.py from coach/START-HERE.md; do not edit.\n'
    header += '// Source SHA-256: ' + hashlib.sha256(source).hexdigest() + '\n'
    lines = ',\n'.join('  ' + json.dumps(line, ensure_ascii=True) for line in text.splitlines(keepends=True))
    return (header + 'globalThis.COACH_INSTRUCTIONS = [\n' + lines + "\n].join('');\n").encode('utf-8')

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if the checked-in instructions are stale.')
    args = parser.parse_args()
    target = ROOT / 'starter/instructions.js'
    expected = generated()
    if args.check:
        if not target.is_file() or target.read_bytes() != expected:
            print('Embedded instructions are stale. Run: python3 starter/build.py', file=sys.stderr)
            return 1
        print('Embedded instructions match coach/START-HERE.md.')
    else:
        target.write_bytes(expected)
        print('Generated starter/instructions.js from coach/START-HERE.md.')
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
